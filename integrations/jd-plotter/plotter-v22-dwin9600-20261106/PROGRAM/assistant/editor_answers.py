"""Checked usage answers for actual editor features, not invented UI controls."""
import re


def lookup(prompt):
    text = re.sub(r'\s+', ' ', prompt.casefold().replace('ё','е')).strip()
    # Transparent question wrappers are not a change to the user's literal text.
    # In particular, the quality-review prompt starts with "Кратко объясни:".
    text = re.sub(r'^пожалуйста\s*[, :]\s*', '', text)
    text = re.sub(r'^(?:кратко|коротко|подробно|простыми словами)\s+', '', text)
    text = re.sub(r'^можешь(?:\s+ли)?(?:\s+ты)?\s+(?:объяснить|рассказать|подсказать)\b',
                  'объясни', text)
    if not re.match(r'(?:как|что|где|можно|зачем|почему|расскажи|объясни|сравни|подскажи|есть)\b', text):
        return None
    if re.search(r'подключ|провод|драйвер|vref|напряжен|датчик',text):
        return None
    has = lambda *words: any(word in text for word in words)
    sections=[]
    if has('объект','соседн') or (has('надпис') and has('выбр','выбор','выдел','одну','одной')):
        sections.append(('object_usage','Выберите объект мышью на предпросмотре или в списке. Можно написать «Выбери объект Марина», '
            'если он однозначно определяется. Затем «Увеличь в 2 раза» относится к нему, а соседи сохраняются. '
            'Геометрическая правка сначала появляется как предложение: проверьте и нажмите «Применить к эскизу», подтвердите. '
            'Это меняет только экранный эскиз, не двигает станок. Рисование запускается отдельно в пульте. '
            'Если имя неоднозначно, выберите нужный объект в списке. '
            'Отдельного окна «Свойства объекта» нет. Выбор сам по себе геометрию не меняет.'))
    if has('автокоп','автосохран','после перезапуск','после закрыт'):
        sections.append(('autosave_usage','«Автосохранение» сохраняет последнюю и предыдущую копии подтверждённого эскиза. '
            '«Восстановить автокопию…» открывает их только на пробном листе: восстанавливаются контуры и проверенные источники текста/объектов. '
            'COM, физический ноль, положение головки и история переписки не восстанавливаются. '
            'Это не обещание сохранения при закрытии: проверяйте сообщения об ошибках, при необходимости сохраните проект вручную.'))
    if has('сохранить проект','сохранение проекта','открыть проект','продолжить редакт','сохранить соседн'):
        sections.append(('editor_projects','«Сохранить проект» сохраняет текущую подтверждённую композицию в .plotter.json с параметрами надписей; '
            'сначала примените или отмените ожидающее предложение. «Открыть проект» позволяет продолжить редактирование достоверных источников. '
            'Сохраняется только эскиз, не COM, физический ноль и реальные координаты. SVG сохраняет только контуры, а не полноценный редактируемый проект.'))
    if has('текстовый блок','межстроч','выравнивание строк') and not has('рукопис','почерк'):
        sections.append(('block_usage','«Инструменты… → Текстовый блок»: текст, ширина/высота прямоугольника, высота заглавных, '
            'интервал букв, межстрочный шаг и выравнивание. Переносы идут по словам; не помещающийся текст отклоняется, '
            'размер не уменьшается скрытно. Пример: «Размести «С днём рождения!» в прямоугольнике 80×40 мм высотой 5 мм». '
            'Результат — предложение, требуется применение к эскизу.'))
    if has('шаблон','открытк') and has('сохран','запом','использ','повтор','как','что'):
        sections.append(('template_usage','«Инструменты… → Шаблоны»: примените композицию, выберите печатный объект для имени, '
            'задайте название шаблона и нажмите «Запомнить текущую композицию». Затем «Моя открытка для Анны» '
            'подготовит предложение на основе сохранённого шаблона. Имя вставляется буквально, падеж не угадывается; '
            'размер листа шаблона не меняется скрытым масштабированием.'))
    if has('три оформлен','три вариант','3 вариант','сравнить вариант'):
        sections.append(('variants_usage','«Сделай три оформления» либо «Инструменты… → Варианты / маршрут» показывает варианты без подмены текста. '
            'Выберите подходящий предпросмотр и отдельно примените к эскизу. Непомещающийся вариант не применяется.'))
    if has('оптимизац','оптимизировать','сократить соедин','маршрут пера'):
        sections.append(('route_usage','«Оптимизируй маршрут» или «Инструменты… → Варианты / маршрут» меняет порядок/направление контуров, '
            'сохраняя их геометрию. До применения сравните длины соединений и оранжевые линии: без подъёма пера они всё равно рисуются. '
            'Софт не может полностью убрать эти линии без механизма подъёма.'))
    if has('истори','повторить','отмена','отменить правк') and has('эскиз','редактор','изменен','правк','как'):
        sections.append(('history_usage','«Отменить последнее»/«Повторить» — до 30 экранных изменений. '
            '«Инструменты… → История» показывает состояния и позволяет вернуться к выбранному. Новая правка очищает ветку повтора. '
            'Это не отменяет выполненное движение станка.'))
    if not sections:
        return None
    return '\n\n'.join(item[1] for item in sections), '+'.join(item[0] for item in sections)
