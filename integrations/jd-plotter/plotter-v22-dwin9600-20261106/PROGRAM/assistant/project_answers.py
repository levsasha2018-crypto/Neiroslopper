def lookup(prompt: str, state: Mapping) -> ProjectAnswer | None:
    """Return reviewed evidence, never a plan or a guessed composite answer."""
    urgent = urgent_answer(prompt)
    if urgent is not None:
        return urgent
    if _literal_print_request(prompt):
        return None
    # Answering only the first of two unrelated questions looks authoritative
    # while silently dropping the other. Ask for one topic instead. Splitting
    # quoted drawing content is deliberately avoided.
    unquoted = _outside_quotes(normalized(prompt))
    clauses = re.split(r"[;?]+\s*|\s+(?:и еще|а еще|а также)\s+|"
                       r"\s+и\s+(?=(?:как|какой|какая|какие|почему|есть ли|что|можно ли|сколько)\b)",
                       unquoted)
    clauses = [clause.strip() for clause in clauses if clause.strip()]
    question_start = r"^(?:почему|как|зачем|что|какой|какая|какие|есть ли|можно ли|сколько)\b"
    independent_questions = (bool(re.match(question_start, clauses[0])) if clauses else False) or (
        sum(bool(re.match(question_start, clause)) for clause in clauses) >= 2)
    if len(clauses) > 1 and independent_questions:
        answers = [_lookup_single(clause, state) for clause in clauses]
        recognized = [answer for answer in answers if answer is not None]
        if recognized and (len({answer.topic for answer in recognized}) > 1 or
                           len(recognized) != len(clauses)):
            return ProjectAnswer(
                "Здесь несколько вопросов с разными условиями. Уточните один: "
                "подключение/безопасность, устройство сборки или подготовка рисунка. "
                "Не буду отвечать только на первую часть и выдавать её за проверку всего "
                "запроса. Настройки и станок не изменялись.", "clarify_topics", (PROJECT, ASSISTANT_GUIDE))
    return _lookup_single(prompt, state)
