def _outside_quotes(prompt: str) -> str:
    """Paired quotes are literal content, not reported physical symptoms."""
    return re.sub(r'«[^»]*»|“[^”]*”|"[^"\n]*"|\'[^\'\n]*\'', " ", prompt)


def _literal_print_request(prompt: str) -> bool:
    """Use the existing whole-request grammar, not a loose quote heuristic."""
    if not re.search(r"напечат|напиши|подготовь", prompt.casefold()):
        return False
    from .planner import parse
    preview = parse(prompt, {"sheet_width": 3000, "sheet_height": 3000,
                             "has_paths": True})
    return preview.kind == "print_text"


def _other_software_topic(text: str) -> bool:
    explicit = (re.search(r"nvidia|geforce|radeon|видеокарт|\bamd\b|"
                          r"драйвер\w*\s+(?:принтер|сетев|звуков)", text) or
                (re.search(r"windows|виндовс", text) and re.search(r"драйвер|принтер", text)))
    plotter = re.search(r"плоттер|каретк|портал|a4988|cloudray|grbl|ардуин|"
                       r"arduino|cnc|shield|шилд|щилд|dwin|мотор|двигател", text)
    return bool(explicit and not plotter)


def urgent_answer(prompt: str) -> ProjectAnswer | None:
    """Read-only priority warning, usable before command parsing or model use.

    This detects a report, not a sensor measurement. A fully parsed literal
    print request and simple explicit negations are not an actual fire.
    """
    # Only the closed print grammar identifies a quoted payload as literal.
    # Ordinary symptom descriptions such as мотор пахнет «горелым» stay visible.
    if _literal_print_request(prompt):
        return None
    text = normalized(re.sub(r'[«»“”"\']', "", prompt))
    text = re.sub(r"\b(?:не\s+(?:дым\w*|искр\w*|обжига\w*|горяч\w*)|"
                  r"не\s+сильно\s+гре\w*|"
                  r"не\s+перегре\w*|(?:нет|без)\s+перегрев\w*|"
                  r"(?:нет|без)\s+(?:дым\w*|искр\w*)|"
                  r"не\s+пах\w*\s+горел\w*|"
                  r"(?:нет|без)\s+запах\w*\s+горел\w*)\b", " ", text)
    english_symptoms = (r"smok(?:e|es|ing|ed)|sparks?|sparking|"
                        r"overheat(?:s|ing|ed)?|(?:too\s+|very\s+)?hot(?:\s+to\s+(?:the\s+)?touch)?|"
                        r"(?:burning|burnt)\s+smell|"
                        r"smell(?:s|ing)?\s+(?:(?:of|like)\s+)?(?:burning|burnt)|burning")
    # Remove only a directly negated symptom phrase; another positive symptom
    # in the same message ("not smoking, but sparking") must still win.
    text = re.sub(r"\b(?:not|no|without|isnt|isn\s+t|arent|aren\s+t|"
                  r"doesnt|doesn\s+t|dont|don\s+t)\s+(?:currently\s+)?(?:" +
                  english_symptoms + r")\b", " ", text)
    symptom = re.search(r"\b(?:дым\w*|искр\w*|запах\w*\s+горел\w*|"
                        r"пах\w*\s+горел\w*|обжига\w*|сильно\s+гре\w*|горяч\w*|"
                        r"перегре\w*|раскален\w*|" + english_symptoms + r")\b", text)
    component = re.search(r"соленоид|электромагнит|реле|мотор|двигател|драйвер|плата|дисплей|экран|провод|плоттер|"
                          r"блок\s+питания|адаптер|разъем|шилд\w*|щилд\w*|ардуин\w*|"
                          r"(?<!\w)(?:a4988|dwin|двин|usb|бп|arduino|cnc|psu|"
                          r"motors?|steppers?|drivers?|boards?|controllers?|shields?|"
                          r"displays?|screens?|wires?|cables?|adapters?|connectors?|"
                          r"power\s+suppl(?:y|ies))(?!\w)", text)
    if symptom and component:
        return ProjectAnswer(
            "Остановите работу и отключите питание устройства. При дыме, искрах или "
            "запахе горелого не включайте его повторно до проверки. Не трогайте горячие "
            "детали и не переставляйте провода под питанием. Для переподключения должны "
            "быть отключены все источники, в том числе USB и моторное питание. "
            "Я не могу отключить станок через чат. Какой компонент нагревается или дымит?",
            "urgent", (PROJECT, A4988))
    return None


def is_display_topic(prompt: str) -> bool:
    """Keep device aliases whole: 'сдвинулся' is not a DWIN display."""
    text = normalized(prompt)
    return (any(word in text for word in ("дисплей", "шлейф")) or
            bool(re.search(r"(?<!\w)(?:dwin|двин|type[ -]*c|тайп(?:[ -]+[сc])?)(?!\w)", text)))


def mentions_forty_steps(prompt: str) -> bool:
    """Require the exact number and a step noun, never '40' inside 240/2400."""
    text = normalized(prompt)
    return (bool(re.search(r"(?<![\w.,])40(?![\w.,])", text)) and
            bool(re.search(r"\bшаг(?:и|а|ов|ах|ами|ом)?\b", text)))


def is_project_topic(prompt: str) -> bool:
    text = normalized(prompt)
    # A GPU/Windows software driver is not an A4988 just because of its name.
    if _other_software_topic(text):
        return False
    return bool(re.search(
        r"плоттер|станок|станк|каретк|портал|головк|мотор|двигател|"
        r"a4988|драйвер|cloudray|grbl|fluidnc|dlc32|\bmks\b|ардуин|arduino|cnc|shield|шилд|щилд|"
        r"соленоид|электромагнит|hcne1|jqc3|coolen|dwin|дисплей|камер|ov5640|esp32|есп32|машинное зрение|сканер|сканир|концев|базир|homing|микрошаг|vref|gt2|шкив|"
        r"обмот|перо|пера|ручк|рисова|эскиз|svg|"
        r"\bлист(?:а|у|ом|е|ы|ов|ам|ами|ах|ок|ка|ку|ком|ке|ки|ков|кам|ками|ках)?\b|бумаг|почерк|"
        r"питан|напряжен|вольт|\busb\b|заземл|(?:соедин|подключ|общая)[^.!?;]{0,25}земл|"
        r"\bgnd\b|\bvmot\b|\bvdd\b|"
        r"распинов|контакт|(?:соедин|подключ)[^.!?;]{0,25}(?:плюс|минус)|разъем|raspberry|"
        r"удержан|\bстрелк|\bрем(?:ень|н[а-я]+|енн[а-я]+|еш[а-я]+)\b", text))


def editor_words_only(prompt: str) -> bool:
    """Paper placement must not turn a safe drawing into a wiring question.

    Do not discard equipment words, quoted hardware, or electrical questions.
    This is used only together with the creative request's whole-input guard.
    """
    from .verified import _hardware_question
    text = normalized(prompt)
    stripped = re.sub(r'\bлист\w*\b|бумаг\w*|рисова\w*|эскиз\w*|\bsvg\b|почерк\w*', ' ', text)
    return is_project_topic(prompt) and not is_project_topic(stripped) and not _hardware_question(text)


def sheet_dimensions(state: Mapping) -> tuple[float, float] | None:
    values = state.get("sheet_width"), state.get("sheet_height")
    if all(isinstance(number, (int, float)) and not isinstance(number, bool) and
           1 <= number <= 3000 and math.isfinite(number) for number in values):
        return values
    return None


