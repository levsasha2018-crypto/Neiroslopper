def normalized(prompt: str) -> str:
    return re.sub(r"\s+", " ", prompt.casefold().replace("ё", "е")).strip()


def uses_v22(state):
    return (state.get('machine_profile') == 'mks_dlc32_fluidnc' and
            state.get('board_revision') not in ('2.0', '2.0_001'))


def pen_motion_description(state: Mapping | None) -> str:
    """Describe an explicit editor profile, never infer mechanics from M8/M9."""
    state = state or {}
    continuous = state.get("pen_continuous") is True
    if state.get("pen_power_raises") is True:
        return ("В выбранном профиле питание ПОДНИМАЕТ ручку: M8 включает катушку и поднимает, "
                "M9 выключает и опускает. Рисунок выполняется без питания катушки; "
                "переходы — с питанием. " +
                ("Выбран непрерывный режим: таймера включения и пауз охлаждения нет; это не тепловая защита. "
                 if continuous else "При длинном переходе нужны остановки для охлаждения; "
                 "в этих точках ручка опускается и может оставлять точки. ") +
                "После задания пульт отправляет отключение. При СТОП или потере связи команда может не дойти; "
                "нельзя считать катушку выключенной без проверки. При необходимости отключите её БП вручную. "
                "Перед камерным проходом снимите ручку или механически закрепите её поднятой: "
                "во время ожидания и съёмки катушка выключена. ")
    if state.get("pen_power_raises") is False:
        return ("В выбранном профиле питание ОПУСКАЕТ ручку: M8 включает катушку и опускает, "
                "M9 выключает; подъём должен обеспечивать проверенный возвратный механизм. "
                + ("Непрерывный режим не вводит таймер и паузы охлаждения. " if continuous else
                   "Длинные штрихи делятся паузами с выключенной катушкой. "))
    return ("M8 включает питание соленоида, M9 выключает его. Физическое направление "
            "задаётся в пульте отдельно: «питание поднимает» или «питание опускает». "
            "В этом снимке редактора направление не передано, поэтому положение ручки не угадываю. ")


